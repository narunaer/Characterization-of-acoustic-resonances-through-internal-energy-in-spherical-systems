DERIV_MATCH_TOL_PERIODS = 0.15       # tolerancia (em periodos) pra herdar D0_confirmado/origem do candidato original
DERIV_MIN_SPAN_OVER_FWHM = 1.5       # exige pelo menos 1.5x a FWHM observada de sobra dos DOIS lados do pico
                                      # dentro da janela -- rejeita "maximos" onde a janela foi truncada pela
                                      # borda do dominio (x_min/x_max) antes de mostrar a curva virando de verdade
DERIV_MIN_RELATIVE_DIP = 0.3         # dois maximos locais adjacentes so contam como picos SEPARADOS se o vale
                                      # entre eles cair pelo menos essa fracao abaixo do menor dos dois; senao
                                      # sao fundidos num so (mantem o mais alto) -- evita fatiar um unico "ombro"
                                      # largo e raso em varios "picos" por causa de uma ondulacao insignificante
DERIV_MAX_WIDTH_XM = MAX_WIDTH_XM    # rejeita picos com FWHM maior que isso (mesmo limite que o pipeline
                                      # original usava no modo "density"): um "maximo" com FWHM ~0.2 (quase 1/4
                                      # do dominio inteiro) e um ombro largo da curva de fundo, nao uma
                                      # ressonancia estreita, mesmo tendo contraste decente contra a vizinhanca


def _richardson_derivative(x_arr, W_arr):
    """dW/dx em cada ponto de uma malha regular, via diferenca central de
    4a ordem (equivale a extrapolacao de Richardson sobre a diferenca
    central simples: usa h e 2h e cancela o termo de erro O(h^2))."""
    n = len(x_arr)
    dW = np.full(n, np.nan)
    h = float(x_arr[1] - x_arr[0])
    if n >= 5:
        dW[2:-2] = (-W_arr[4:] + 8*W_arr[3:-1] - 8*W_arr[1:-3] + W_arr[0:-4]) / (12*h)
    if n >= 3:
        if np.isnan(dW[1]):
            dW[1] = (W_arr[2] - W_arr[0]) / (2*h)
        if np.isnan(dW[-2]):
            dW[-2] = (W_arr[-1] - W_arr[-3]) / (2*h)
    dW[0] = (W_arr[1] - W_arr[0]) / h
    dW[-1] = (W_arr[-1] - W_arr[-2]) / h
    return dW


def _merge_shallow_split_peaks(peaks, m, rho_ratio, lmax, min_relative_dip=DERIV_MIN_RELATIVE_DIP,
                                n_valley_samples=120):
    """
    Dois maximos locais adjacentes as vezes sao, na pratica, a mesma
    "corcova" larga fatiada em dois por uma ondulacao rasa (ex: 1% de
    queda no meio de um platô). Isso NAO e uma segunda ressonancia
    separada -- fisicamente so conta como pico distinto quando o vale
    entre eles cai de verdade (ex: perto de um zero de D0, queda de
    ordens de grandeza). Aqui, pra cada par de picos vizinhos (em x),
    mede-se o minimo de W entre eles; se esse vale nao cair pelo menos
    `min_relative_dip` abaixo do MENOR dos dois picos, eles sao fundidos
    (mantém-se so o mais alto). Repete ate estabilizar (cobre o caso de
    3+ picos proximos em cadeia).
    """
    if len(peaks) < 2:
        return peaks
    peaks = sorted(peaks, key=lambda p: p['xM_peak'])
    changed = True
    while changed and len(peaks) >= 2:
        changed = False
        merged = []
        i = 0
        while i < len(peaks):
            if i + 1 < len(peaks):
                p1, p2 = peaks[i], peaks[i + 1]
                xv = np.linspace(p1['xM_peak'], p2['xM_peak'], n_valley_samples)
                Wv = sphere_total_energy_vs_xM(xv, m, rho_ratio, lmax)
                validv = np.isfinite(Wv) & (Wv > 0)
                if validv.sum() >= 5:
                    W_valley = float(np.min(Wv[validv]))
                    shorter = min(p1['WT_peak'], p2['WT_peak'])
                    if shorter > 0:
                        dip_ratio = (shorter - W_valley) / shorter
                        if dip_ratio < min_relative_dip:
                            keep = p1 if p1['WT_peak'] >= p2['WT_peak'] else p2
                            merged.append(keep)
                            i += 2
                            changed = True
                            continue
            merged.append(peaks[i])
            i += 1
        peaks = merged
    return peaks


def _detectar_picos_por_derivada(m, rho_ratio, lmax, x_min, x_max, candidatos_originais=None,
                                  points_per_period=DERIV_POINTS_PER_PERIOD,
                                  min_points=DERIV_MIN_POINTS, max_points=DERIV_MAX_POINTS,
                                  local_window_frac=DERIV_LOCAL_WINDOW_FRAC, n_local=DERIV_N_LOCAL,
                                  match_tol_periods=DERIV_MATCH_TOL_PERIODS,
                                  min_span_over_fwhm=DERIV_MIN_SPAN_OVER_FWHM,
                                  max_width=DERIV_MAX_WIDTH_XM):
    """
    Deteccao definitiva de picos exigindo apenas o criterio de derivada
    (maximo local verdadeiro), em 2 chamadas vetorizadas:
      1) LOCALIZAR: 1 varredura no dominio inteiro, resolucao ligada ao
         periodo fisico esperado pi/m -> posicoes aproximadas dos maximos.
      2) REFINAR+MEDIR: constroi, para CADA candidato, uma janela local
         propria (sem duplicar pontos quando cai perto de x_min/x_max) e
         avalia W nela numa unica chamada vetorizada (rapido mesmo com
         centenas/milhares de picos, regime de m grande).
    Depois de confirmar que e um maximo local verdadeiro (d2W/dx2<0), so
    aceita o pico se a janela observada tiver sobrado pelo menos
    min_span_over_fwhm vezes a FWHM medida em AMBOS os lados -- isso rejeita
    "maximos" que na verdade sao a curva ainda subindo/descendo quando bate
    no limite do dominio (janela truncada, comum perto de x_min ou x_max),
    e so aceita algo como pico de verdade quando da pra ver a curva virar
    com folga nos dois lados.
    Se `candidatos_originais` (saida de _detect_velocity_mode /
    _detect_density_mode) for passado, cada pico confirmado herda
    D0_confirmado / xM_D0 / origem do candidato original mais proximo,
    quando a distancia for <= match_tol_periods * periodo.
    """
    m_eff = max(float(m), 1e-9)
    period_est = np.pi / m_eff
    n_points = int(np.clip(points_per_period * (x_max - x_min) / period_est, min_points, max_points))
    xs = np.linspace(x_min, x_max, n_points)
    Ws = sphere_total_energy_vs_xM(xs, m, rho_ratio, lmax)
    valid = np.isfinite(Ws) & (Ws > 0)
    if valid.sum() < 10:
        return []
    if not valid.all():
        idxs = np.arange(len(Ws))
        Ws = np.interp(idxs, idxs[valid], Ws[valid])
    dW = _richardson_derivative(xs, Ws)
    sign = np.sign(dW)
    cross_down = np.where((sign[:-1] > 0) & (sign[1:] <= 0))[0]
    cross_down = cross_down[(cross_down >= 2) & (cross_down <= len(xs) - 3)]
    if len(cross_down) == 0:
        return []
    approx_roots = []
    for idx in cross_down:
        x_a, x_b = xs[idx], xs[idx + 1]
        d_a, d_b = dW[idx], dW[idx + 1]
        if d_b == d_a:
            continue
        approx_roots.append(x_a + (0.0 - d_a) * (x_b - x_a) / (d_b - d_a))
    if not approx_roots:
        return []
    approx_roots = np.array(approx_roots, dtype=float)
    n_peaks = len(approx_roots)

    window = max(local_window_frac * period_est, 1e-7)
    # janela PROPRIA por candidato (lo_i, hi_i), sem duplicar pontos quando
    # cai perto de x_min/x_max -- np.clip criava pontos repetidos na borda,
    # o que gerava "maximos" espurios exatamente onde a curva so estava
    # ainda subindo/descendo ao bater no limite do dominio.
    lo_arr = np.maximum(x_min, approx_roots - window)
    hi_arr = np.minimum(x_max, approx_roots + window)
    frac = np.linspace(0.0, 1.0, n_local)
    X_mat = lo_arr[:, None] + frac[None, :] * (hi_arr - lo_arr)[:, None]
    flat_W = sphere_total_energy_vs_xM(X_mat.ravel(), m, rho_ratio, lmax)
    W_mat = flat_W.reshape(n_peaks, n_local)

    result = []
    for i in range(n_peaks):
        xi, Wi, x0 = X_mat[i], W_mat[i], approx_roots[i]
        validi = np.isfinite(Wi) & (Wi > 0)
        if validi.sum() < 10:
            continue
        if not validi.all():
            idxs = np.arange(len(Wi))
            Wi = np.interp(idxs, idxs[validi], Wi[validi])
        dWi = _richardson_derivative(xi, Wi)
        signi = np.sign(dWi)
        crossi = np.where((signi[:-1] > 0) & (signi[1:] <= 0))[0]
        if len(crossi) == 0:
            continue
        centers = xi[crossi]
        j = crossi[np.argmin(np.abs(centers - x0))]
        x_a, x_b = xi[j], xi[j + 1]
        d_a, d_b = dWi[j], dWi[j + 1]
        if d_b == d_a:
            continue
        root = x_a + (0.0 - d_a) * (x_b - x_a) / (d_b - d_a)
        h2 = float(xi[1] - xi[0])
        i_near = int(np.argmin(np.abs(xi - root)))
        i_near = min(max(i_near, 1), len(Wi) - 2)
        d2 = (Wi[i_near + 1] - 2 * Wi[i_near] + Wi[i_near - 1]) / h2 ** 2
        if not (np.isfinite(d2) and d2 < 0):
            continue  # nao e concavo p/ baixo -> nao e maximo real, descarta
        WT_peak = float(Wi[i_near])
        outer = np.abs(xi - root) > 0.7 * window
        background = float(np.median(Wi[outer])) if outer.sum() >= 10 else float(np.median(Wi))
        half = background + 0.5 * (WT_peak - background)
        fwhm = np.nan
        if half > background:
            xl = xi[0]
            for k in range(i_near, 0, -1):
                if Wi[k] >= half and Wi[k - 1] < half:
                    w_a, w_b = Wi[k - 1], Wi[k]
                    xl = xi[k - 1] + (half - w_a) * (xi[k] - xi[k - 1]) / (w_b - w_a) if w_b != w_a else xi[k - 1]
                    break
            xr = xi[-1]
            for k in range(i_near, len(xi) - 1):
                if Wi[k] >= half and Wi[k + 1] < half:
                    w_a, w_b = Wi[k], Wi[k + 1]
                    xr = xi[k] + (half - w_a) * (xi[k + 1] - xi[k]) / (w_b - w_a) if w_b != w_a else xi[k + 1]
                    break
            if xr > xl:
                fwhm = xr - xl
        if not np.isfinite(fwhm) or fwhm <= 0:
            continue  # sem FWHM confiavel -> nao da pra validar o formato, descarta
        left_span = root - xi[0]
        right_span = xi[-1] - root
        if left_span < min_span_over_fwhm * fwhm or right_span < min_span_over_fwhm * fwhm:
            continue  # janela truncada perto demais do pico -> nao confirma (provavel borda do dominio)
        if fwhm > max_width:
            continue  # largo demais pra ser resonancia estreita (ombro da curva de fundo, nao pico)
        q = root / fwhm
        result.append({'xM_peak': float(root), 'FWHM': float(fwhm),
                        'Q': float(q), 'WT_peak': WT_peak,
                        'd2W_dx2': float(d2), 'origem': 'derivada_periodo',
                        'D0_confirmado': False, 'xM_D0': np.nan})
    result.sort(key=lambda p: p['xM_peak'])

    # deduplica: dois candidatos vizinhos (comum quando a malha global estava
    # sub-amostrada) podem convergir pro mesmo maximo real
    dedup = []
    tol = max(0.05 * period_est, 1e-7)
    for p in result:
        if dedup and (p['xM_peak'] - dedup[-1]['xM_peak']) < tol:
            continue
        dedup.append(p)

    # funde picos adjacentes separados por um vale raso demais (mesma
    # "corcova" larga fatiada em 2+ por ondulacao insignificante, nao 2
    # ressonancias de verdade)
    dedup = _merge_shallow_split_peaks(dedup, m, rho_ratio, lmax)

    # herda metadados (D0_confirmado, xM_D0, origem) do candidato original
    # mais proximo, quando existir correspondencia dentro da tolerancia
    if candidatos_originais:
        match_tol = max(match_tol_periods * period_est, 1e-6)
        orig_x = np.array([c['xM_peak'] for c in candidatos_originais], dtype=float)
        for p in dedup:
            dists = np.abs(orig_x - p['xM_peak'])
            j = int(np.argmin(dists))
            if dists[j] <= match_tol:
                orig = candidatos_originais[j]
                p['D0_confirmado'] = bool(orig.get('D0_confirmado', False))
                p['xM_D0'] = orig.get('xM_D0', np.nan)
                if orig.get('D0_confirmado', False):
                    p['origem'] = 'zoom_D0'
                elif orig.get('origem'):
                    p['origem'] = orig.get('origem')
    return dedup


def J(n, x):
    x = np.asarray(x, dtype=float)
    if n >= 0:
        return spherical_jn(n, x)
    return (-1) ** (-n - 1) * spherical_yn(-n - 1, x)

def Y(n, x):
    x = np.asarray(x, dtype=float)
    if n >= 0:
        return spherical_yn(n, x)
    return (-1) ** (-n) * spherical_jn(-n - 1, x)

def dJ(n, x):
    x = np.asarray(x, dtype=float)
    if n >= 0:
        return spherical_jn(n, x, derivative=True)
    return (-1) ** (-n - 1) * spherical_yn(-n - 1, x, derivative=True)

def dY(n, x):
    x = np.asarray(x, dtype=float)
    if n >= 0:
        return spherical_yn(n, x, derivative=True)
    return (-1) ** (-n) * spherical_jn(-n - 1, x, derivative=True)

def H(n, x):
    return J(n, x) + 1j * Y(n, x)

def dH(n, x):
    return dJ(n, x) + 1j * dY(n, x)

def sphere_energy_parts_vs_xM(xM_vals, m, rho_ratio, lmax):
    """Return total, potential, and kinetic internal energy."""
    xM_vals = np.asarray(xM_vals, dtype=float)
    if np.any(xM_vals <= 0.0):
        raise ValueError("All x_M values must be positive.")
    if not np.isfinite(m) or m <= 0.0:
        raise ValueError("m must be positive and finite.")
    if not np.isfinite(rho_ratio) or rho_ratio <= 0.0:
        raise ValueError("rho_ratio must be positive and finite.")
    m_t = float(m) / float(rho_ratio)
    rhoM_over_rhoS = 1.0 / float(rho_ratio)
    xS_vals = float(m) * xM_vals
    WP = np.zeros_like(xM_vals, dtype=float)
    WK = np.zeros_like(xM_vals, dtype=float)
    for ell in range(int(lmax) + 1):
        jS = J(ell, xS_vals)
        djS = dJ(ell, xS_vals)
        hM = H(ell, xM_vals)
        dhM = dH(ell, xM_vals)
        denominator = jS * dhM - m_t * djS * hM
        b_ell = np.zeros_like(xM_vals, dtype=complex)
        valid = np.isfinite(denominator) & (np.abs(denominator) > 1.0e-300)
        b_ell[valid] = (
            1j * rhoM_over_rhoS / (xM_vals[valid] ** 2 * denominator[valid])
        )
        modal_weight = (2 * ell + 1) * np.abs(b_ell) ** 2
        radial_integral = 0.5 * xS_vals ** 3 * (
            jS ** 2 - J(ell - 1, xS_vals) * J(ell + 1, xS_vals)
        )
        boundary_term = xS_vals ** 2 * jS * djS
        WP += modal_weight * np.real(radial_integral)
        WK += modal_weight * np.real(radial_integral + boundary_term)
    WP = np.where(np.isfinite(WP) & (WP >= 0.0), WP, 0.0)
    WK = np.where(np.isfinite(WK) & (WK >= 0.0), WK, 0.0)
    WT = np.real(WP + WK)
    WT = np.where(np.isfinite(WT) & (WT > 0.0), WT, 0.0)
    return WT, WP, WK

def sphere_total_energy_vs_xM(xM_vals, m, rho_ratio, lmax):
    WT, _, _ = sphere_energy_parts_vs_xM(
        xM_vals=xM_vals, m=m, rho_ratio=rho_ratio, lmax=lmax,
    )
    return WT

def D_l_sphere(l, xM, m, rho_ratio):
    xM = np.asarray(xM, dtype=float)
    m_t = float(m) / float(rho_ratio)
    xS = float(m) * xM
    jS = J(l, xS)
    djS = dJ(l, xS)
    hM = H(l, xM)
    dhM = dH(l, xM)
    return jS * dhM - m_t * djS * hM

def absD0_2_sphere(xM, m, rho_ratio):
    xM = np.asarray(xM, dtype=float)
    with np.errstate(all="ignore"):
        D = D_l_sphere(0, xM, m, rho_ratio)
    return np.real(D) ** 2 + np.imag(D) ** 2

def find_D0_candidates(m, rho_ratio, x_min=X_MIN, x_max=X_MAX, n_coarse=6000):
    x = np.linspace(x_min, x_max, int(n_coarse))
    vals = absD0_2_sphere(x, m, rho_ratio)
    valid_triplets = np.isfinite(vals[:-2]) & np.isfinite(vals[1:-1]) & np.isfinite(vals[2:])
    local_minimum = (vals[1:-1] < vals[:-2]) & (vals[1:-1] < vals[2:])
    mins_idx = np.flatnonzero(valid_triplets & local_minimum) + 1
    xs = []
    for i in mins_idx:
        lo = x[max(i - 2, 0)]
        hi = x[min(i + 2, len(x) - 1)]
        res = minimize_scalar(
            lambda xx: absD0_2_sphere(xx, m, rho_ratio),
            bounds=(lo, hi),
            method="bounded",
            options={"xatol": 1e-13},
        )
        if res.success and np.isfinite(res.x):
            xs.append(float(res.x))
    if not xs:
        return np.array([], dtype=float)
    return np.unique(np.asarray(xs, dtype=float))

def _d0_background_ratio(xc, m, rho_ratio, x_min, x_max):
    val = absD0_2_sphere(xc, m, rho_ratio)
    x_background = np.concatenate([np.linspace(xc * 0.5, xc * 0.9, 25), np.linspace(xc * 1.1, xc * 1.5, 25)])
    x_background = x_background[(x_background > x_min) & (x_background < x_max)]
    if len(x_background) == 0 or not np.isfinite(val):
        return np.inf
    background_values = absD0_2_sphere(x_background, m, rho_ratio)
    background_values = background_values[np.isfinite(background_values) & (background_values > 0.0)]
    if len(background_values) == 0:
        return np.inf
    background = np.median(background_values)
    if background <= 0.0:
        return np.inf
    return float(val / background)

def prepare_log_signal(W):
    W = np.asarray(W, dtype=float)
    valid = np.isfinite(W) & (W > 0.0)
    if np.count_nonzero(valid) < 5:
        return None
    floor = max(np.min(W[valid]) * 1e-14, np.finfo(float).tiny)
    Wc = np.where(valid, W, floor)
    return np.log10(np.maximum(Wc, floor))

def _peaks_on_grid(x_mesh, W, prominence_min, distance_min=1, max_width=None):
    """Detect peaks on a sampled energy curve."""
    x_mesh = np.asarray(x_mesh, dtype=float)
    W = np.asarray(W, dtype=float)
    ylog = prepare_log_signal(W)
    if ylog is None:
        return []
    distance_min = max(1, min(int(distance_min), len(ylog) - 1))
    idx, _ = find_peaks(ylog, prominence=prominence_min, distance=distance_min)
    idx = idx[(idx >= 3) & (idx <= len(x_mesh) - 4)]
    if len(idx) == 0:
        return []
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        _, _, lips, rips = peak_widths(W, idx, rel_height=0.5)
    sample_axis = np.arange(len(x_mesh), dtype=float)
    xl = np.interp(lips, sample_axis, x_mesh)
    xr = np.interp(rips, sample_axis, x_mesh)
    out = []
    for k, i in enumerate(idx):
        x0 = float(x_mesh[i])
        fwhm = float(xr[k] - xl[k])
        WT_peak = float(W[i])
        if not np.isfinite(fwhm) or fwhm <= 0.0 or not np.isfinite(WT_peak) or WT_peak <= 0.0:
            continue
        if max_width is not None and fwhm > max_width:
            continue
        out.append({"xM_peak": x0, "FWHM": fwhm, "Q": x0 / fwhm, "WT_peak": WT_peak})
    return out

def _peak_background_ratio(xc, WT_peak, fwhm, x_mesh, W):
    """Return the peak-to-background energy ratio."""
    margin = max(30.0 * fwhm, 0.1 * xc)
    x_background = np.concatenate([
        np.linspace(xc - 2.0 * margin, xc - margin, 25),
        np.linspace(xc + margin, xc + 2.0 * margin, 25),
    ])
    x_background = x_background[(x_background >= x_mesh[0]) & (x_background <= x_mesh[-1])]
    if len(x_background) == 0 or not np.isfinite(WT_peak) or WT_peak <= 0.0:
        return 0.0
    W_background = np.interp(x_background, x_mesh, W)
    W_background = W_background[np.isfinite(W_background) & (W_background > 0.0)]
    if len(W_background) == 0:
        return np.inf
    background = np.median(W_background)
    if background <= 0.0:
        return np.inf
    return float(WT_peak / background)

def _confirm_D0_by_energy_velocity(xc, x_mesh, W_total, m, rho_ratio, x_min, x_max, lmax):
    """Confirm a D0 candidate using the local energy contrast."""
    x_background = np.concatenate([np.linspace(xc * 0.5, xc * 0.9, 25), np.linspace(xc * 1.1, xc * 1.5, 25)])
    x_background = x_background[(x_background > x_min) & (x_background < x_max)]
    if len(x_background) == 0:
        return False
    W_xc = sphere_total_energy_vs_xM(np.array([xc]), m, rho_ratio, lmax)[0]
    W_background = np.interp(x_background, x_mesh, W_total)
    W_background = W_background[np.isfinite(W_background) & (W_background > 0.0)]
    if len(W_background) == 0 or not np.isfinite(W_xc) or W_xc <= 0.0:
        return False
    background = np.median(W_background)
    return bool(background > 0.0 and W_xc > MIN_ENERGY_RATIO * background)

def nonuniform_global_grid(x_min=X_MIN, x_max=X_MAX, x_split=0.1, n_low=1500, n_high=1500):
    if not (0.0 < x_min < x_max):
        raise ValueError("Require 0 < x_min < x_max.")
    x_split = float(np.clip(x_split, x_min, x_max))
    n_low = max(int(n_low), 2)
    n_high = max(int(n_high), 2)
    if x_split <= x_min:
        return np.linspace(x_min, x_max, n_low + n_high)
    if x_split >= x_max:
        return np.geomspace(x_min, x_max, n_low + n_high)
    low = np.geomspace(x_min, x_split, n_low, endpoint=False)
    high = np.linspace(x_split, x_max, n_high)
    return np.unique(np.concatenate([low, high]))

def _neighbor_candidate_distances(candidates, x_min, x_max):
    candidates = np.asarray(candidates, dtype=float)
    if len(candidates) == 0:
        return np.array([], dtype=float)
    if len(candidates) == 1:
        return np.array([x_max - x_min], dtype=float)
    left_distance = np.empty_like(candidates)
    right_distance = np.empty_like(candidates)
    left_distance[0] = candidates[0] - x_min
    left_distance[1:] = np.diff(candidates)
    right_distance[:-1] = np.diff(candidates)
    right_distance[-1] = x_max - candidates[-1]
    return np.minimum(left_distance, right_distance)

def _measure_D0_candidate_with_zoom(xc, m, rho_ratio, x_min, x_max, max_allowed_window, lmax,
                                  prominence_min, distance_min=1, max_width=None):
    for base_window in ZOOM_WINDOWS:
        window = min(float(base_window), float(max_allowed_window))
        if window <= 0.0:
            continue
        lo = max(x_min, xc - window)
        hi = min(x_max, xc + window)
        if hi <= lo:
            continue
        x_local = np.linspace(lo, hi, ZOOM_POINTS)
        W_local = sphere_total_energy_vs_xM(x_local, m, rho_ratio, lmax)
        peaks = _peaks_on_grid(x_local, W_local, prominence_min=prominence_min,
                                  distance_min=distance_min, max_width=max_width)
        if len(peaks) == 0:
            continue
        nearest_index = int(np.argmin([abs(p["xM_peak"] - xc) for p in peaks]))
        peak = dict(peaks[nearest_index])
        dx_local = float(np.median(np.diff(x_local)))
        local_tolerance = max(MIN_MATCH_TOLERANCE, MATCH_TOLERANCE_FACTOR * dx_local)
        if abs(peak["xM_peak"] - xc) <= max(local_tolerance, 0.1 * window):
            return peak
    return None

def _detect_velocity_mode(x_mesh, W_total, local_spacing, d0_candidates, neighbor_distance,
                             m, rho_ratio, x_min, x_max, lmax, max_match_tolerance):
    global_peaks = _peaks_on_grid(x_mesh, W_total, prominence_min=VELOCITY_MIN_PROMINENCE)
    result = []
    for peak in global_peaks:
        item = dict(peak)
        item["origem"] = "malha_global"
        item["D0_confirmado"] = False
        item["xM_D0"] = np.nan
        result.append(item)
    for xc, neighbor_gap in zip(d0_candidates, neighbor_distance):
        d0_ratio = _d0_background_ratio(xc, m, rho_ratio, x_min, x_max)
        if d0_ratio > MAX_D0_BACKGROUND_RATIO:
            continue
        spacing_here = float(np.interp(xc, x_mesh, local_spacing))
        tolerance = max(MIN_MATCH_TOLERANCE, MATCH_TOLERANCE_FACTOR * spacing_here)
        tolerance = min(tolerance, float(max_match_tolerance))
        if len(result) > 0:
            distances = np.array([abs(p["xM_peak"] - xc) for p in result], dtype=float)
            nearest_index = int(np.argmin(distances))
            if distances[nearest_index] <= tolerance:
                result[nearest_index]["D0_confirmado"] = True
                result[nearest_index]["xM_D0"] = float(xc)
                continue
        max_window = max(float(neighbor_gap) / 2.0, 1e-6)
        recovered = _measure_D0_candidate_with_zoom(
            xc, m, rho_ratio, x_min, x_max, max_window, lmax,
            prominence_min=VELOCITY_MIN_PROMINENCE,
        )
        if recovered is None:
            continue
        if not _confirm_D0_by_energy_velocity(xc, x_mesh, W_total, m, rho_ratio, x_min, x_max, lmax):
            continue
        if len(result) > 0:
            distances = np.array([abs(p["xM_peak"] - recovered["xM_peak"]) for p in result], dtype=float)
            nearest_index = int(np.argmin(distances))
            if distances[nearest_index] <= tolerance:
                result[nearest_index]["D0_confirmado"] = True
                result[nearest_index]["xM_D0"] = float(xc)
                continue
        recovered = dict(recovered)
        recovered["origem"] = "zoom_D0"
        recovered["D0_confirmado"] = True
        recovered["xM_D0"] = float(xc)
        result.append(recovered)
    q_min = Q_MIN_MANY_PEAKS if len(result) > MANY_PEAKS_THRESHOLD else Q_MIN_BASE
    for peak in result:
        peak["acima_do_qmin"] = bool(peak["Q"] >= q_min)
        peak["largura_fina"] = bool(peak["FWHM"] <= FWHM_MAX)
        peak["q_min_usado"] = float(q_min)
    return result

def _detect_density_mode(x_mesh, W_total, local_spacing, d0_candidates, neighbor_distance,
                            m, rho_ratio, x_min, x_max, lmax, max_match_tolerance):
    global_peaks = _peaks_on_grid(x_mesh, W_total, prominence_min=DENSITY_MIN_PROMINENCE,
                                      distance_min=MIN_SAMPLE_DISTANCE, max_width=MAX_WIDTH_XM)
    result = []
    for peak in global_peaks:
        peak_ratio = _peak_background_ratio(peak["xM_peak"], peak["WT_peak"], peak["FWHM"], x_mesh, W_total)
        if peak_ratio < MIN_PEAK_BACKGROUND_RATIO:
            continue
        item = dict(peak)
        item["origem"] = "malha_global"
        item["D0_confirmado"] = False
        item["xM_D0"] = np.nan
        result.append(item)
    for xc, neighbor_gap in zip(d0_candidates, neighbor_distance):
        d0_ratio = _d0_background_ratio(xc, m, rho_ratio, x_min, x_max)
        if d0_ratio > MAX_D0_BACKGROUND_RATIO:
            continue
        spacing_here = float(np.interp(xc, x_mesh, local_spacing))
        tolerance = max(MIN_MATCH_TOLERANCE, MATCH_TOLERANCE_FACTOR * spacing_here)
        tolerance = min(tolerance, float(max_match_tolerance))
        if len(result) > 0:
            distances = np.array([abs(p["xM_peak"] - xc) for p in result], dtype=float)
            nearest_index = int(np.argmin(distances))
            if distances[nearest_index] <= tolerance:
                result[nearest_index]["D0_confirmado"] = True
                result[nearest_index]["xM_D0"] = float(xc)
                continue
        max_window = max(float(neighbor_gap) / 2.0, 1e-6)
        recovered = _measure_D0_candidate_with_zoom(
            xc, m, rho_ratio, x_min, x_max, max_window, lmax,
            prominence_min=DENSITY_MIN_PROMINENCE,
            distance_min=MIN_SAMPLE_DISTANCE,
            max_width=MAX_WIDTH_XM,
        )
        if recovered is None:
            continue
        peak_ratio = _peak_background_ratio(xc, recovered["WT_peak"], recovered["FWHM"], x_mesh, W_total)
        if peak_ratio < MIN_PEAK_BACKGROUND_RATIO:
            continue
        if len(result) > 0:
            distances = np.array([abs(p["xM_peak"] - recovered["xM_peak"]) for p in result], dtype=float)
            nearest_index = int(np.argmin(distances))
            if distances[nearest_index] <= tolerance:
                result[nearest_index]["D0_confirmado"] = True
                result[nearest_index]["xM_D0"] = float(xc)
                continue
        recovered = dict(recovered)
        recovered["origem"] = "zoom_D0"
        recovered["D0_confirmado"] = True
        recovered["xM_D0"] = float(xc)
        result.append(recovered)
    return result

def detect_sphere(m, rho_ratio, x_min=X_MIN, x_max=X_MAX,
                     n_global_points=N_GLOBAL_POINTS, lmax=LMAX,
                     max_match_tolerance=2e-3, limiar_alternancia=MODE_SWITCH_PEAK_THRESHOLD):
    lmax = int(lmax)
    if lmax < 0:
        raise ValueError("lmax must be non-negative.")
    n_global_points = max(int(n_global_points), 20)
    n_low = n_global_points // 2
    n_high = n_global_points - n_low
    x_mesh = nonuniform_global_grid(x_min=x_min, x_max=x_max, n_low=n_low, n_high=n_high)
    local_spacing = np.gradient(x_mesh)
    W_total = sphere_total_energy_vs_xM(x_mesh, m, rho_ratio, lmax)
    probe_peaks = _peaks_on_grid(x_mesh, W_total, prominence_min=VELOCITY_MIN_PROMINENCE)
    mode = "velocity" if len(probe_peaks) > limiar_alternancia else "density"
    d0_candidates = np.sort(find_D0_candidates(m, rho_ratio, x_min=x_min, x_max=x_max))
    neighbor_distance = _neighbor_candidate_distances(d0_candidates, x_min, x_max)
    if mode == "velocity":
        result = _detect_velocity_mode(
            x_mesh, W_total, local_spacing, d0_candidates, neighbor_distance,
            m, rho_ratio, x_min, x_max, lmax, max_match_tolerance,
        )
    else:
        result = _detect_density_mode(
            x_mesh, W_total, local_spacing, d0_candidates, neighbor_distance,
            m, rho_ratio, x_min, x_max, lmax, max_match_tolerance,
        )

    # confirma/redetecta os picos exigindo a condicao de maximo local
    # verdadeiro (dW/dx=0 trocando de sinal, d2W/dx2<0); `result` (deteccao
    # original) e usado so pra herdar metadados (D0_confirmado, origem)
    if USE_DERIVATIVE_CONFIRMATION:
        result = _detectar_picos_por_derivada(
            m=m, rho_ratio=rho_ratio, lmax=lmax, x_min=x_min, x_max=x_max,
            candidatos_originais=result,
        )

    q_min = Q_MIN_MANY_PEAKS if len(result) > MANY_PEAKS_THRESHOLD else Q_MIN_BASE
    for peak in result:
        peak["modo_deteccao"] = mode
        peak["lmax_usado"] = lmax
        if mode == "velocity":
            peak["acima_do_qmin"] = bool(peak["Q"] >= q_min) if np.isfinite(peak.get("Q", np.nan)) else False
            peak["largura_fina"] = bool(peak["FWHM"] <= FWHM_MAX) if np.isfinite(peak.get("FWHM", np.nan)) else False
            peak["q_min_usado"] = float(q_min)
        else:
            peak["acima_do_qmin"] = np.nan
            peak["largura_fina"] = bool(peak["FWHM"] <= MAX_WIDTH_XM) if np.isfinite(peak.get("FWHM", np.nan)) else False
            peak["q_min_usado"] = np.nan
    result.sort(key=lambda p: p["xM_peak"])
    return result

