def calculate_metrics(y_true, y_pred):
    y_true, y_pred = np.asarray(y_true, dtype=float), np.asarray(y_pred, dtype=float)
    valid = np.isfinite(y_true) & np.isfinite(y_pred)
    y_true, y_pred = y_true[valid], y_pred[valid]
    if len(y_true) == 0:
        return {"N": 0, "r": np.nan, "R2": np.nan, "RMSE": np.nan, "MAE": np.nan, "MAPE_percent": np.nan}
    residuals = y_true - y_pred
    r_pearson = float(np.corrcoef(y_true, y_pred)[0, 1]) if len(y_true) >= 2 else np.nan
    ss_res = float(np.sum(residuals ** 2))
    ss_tot = float(np.sum((y_true - np.mean(y_true)) ** 2))
    r2 = 1.0 - ss_res / ss_tot if not np.isclose(ss_tot, 0.0) else np.nan
    rmse = float(np.sqrt(np.mean(residuals ** 2)))
    mae = float(np.mean(np.abs(residuals)))
    positive_y = np.abs(y_true) > 1e-15
    mape = float(100.0 * np.mean(np.abs(residuals[positive_y] / y_true[positive_y]))) if np.any(positive_y) else np.nan
    return {"N": int(len(y_true)), "r": r_pearson, "R2": r2, "RMSE": rmse, "MAE": mae, "MAPE_percent": mape}


def coefficient_standard_errors(X, y, coefficients):
    """Erro padrão de mínimos quadrados: sigma^2=RSS/(n-p), Cov=sigma^2*(X^T X)^-1."""
    X, y, coefficients = np.asarray(X, dtype=float), np.asarray(y, dtype=float), np.asarray(coefficients, dtype=float)
    residuals = y - X @ coefficients
    n, p = X.shape
    dof = max(n - p, 1)
    sigma2 = float(np.sum(residuals ** 2) / dof)
    cov = sigma2 * np.linalg.pinv(X.T @ X)
    return np.sqrt(np.diag(cov))


def classifier_score(m, rho_ratio, coefficients):
    m, rho_ratio = np.asarray(m, dtype=float), np.asarray(rho_ratio, dtype=float)
    lm, lr = np.log(m), np.log(rho_ratio)
    terms = np.array([np.ones_like(lm), lm, lr, lm**2, lm * lr, lr**2])
    return np.tensordot(np.asarray(coefficients, dtype=float), terms, axes=(0, 0))


def classifier_probability(m, rho_ratio, coefficients):
    score = classifier_score(m, rho_ratio, coefficients)
    return 1.0 / (1.0 + np.exp(-np.clip(score, -700.0, 700.0)))


def classifier_coefficient_standard_errors(m, rho_ratio, effective_coefficients):
    """Erro de Fisher: Cov(beta)=(X^T W X)^-1, W=diag(p(1-p)), avaliada nos
    coeficientes efetivos já ajustados. Válido com regularização ~nula (C=1e6)."""
    m, rho_ratio = np.asarray(m, dtype=float), np.asarray(rho_ratio, dtype=float)
    lm, lr = np.log(m), np.log(rho_ratio)
    terms = np.column_stack([np.ones_like(lm), lm, lr, lm**2, lm * lr, lr**2])
    p = classifier_probability(m, rho_ratio, effective_coefficients)
    weights = np.clip(p * (1.0 - p), 1e-12, None)
    fisher_info = terms.T @ (terms * weights[:, None])
    return np.sqrt(np.diag(np.linalg.pinv(fisher_info)))


def format_bold_pm_error(value, error, sig_figs=2):
    """Formata 'value' em LaTeX como 'valor \\pm erro' com os dígitos
    incertos em negrito, ambos arredondados na casa decimal do erro."""
    value, error = float(value), float(error)
    if not math.isfinite(error) or error == 0:
        return rf"${value:+.6f}$"

    exp_err = math.floor(math.log10(abs(error)))
    decimals = max(-(exp_err - (sig_figs - 1)), 0)
    val_str = f"{value:+.{decimals}f}"

    if decimals == 0:
        bold_len = min(sig_figs, len(val_str) - 1)
        head, tail = val_str[:-bold_len], val_str[-bold_len:]
    else:
        sign_int, frac = val_str.split(".")
        bold_len = min(sig_figs, len(frac))
        head = sign_int + "." + frac[:-bold_len] if bold_len < len(frac) else sign_int + "."
        tail = frac[-bold_len:]

    bold_value = rf"{head}\mathbf{{{tail}}}"
    error_str = f"{error:.{decimals}f}"
    return rf"${bold_value} \pm {error_str}$"


