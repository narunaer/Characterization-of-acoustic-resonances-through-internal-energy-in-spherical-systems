def sphere_reference_fluid_sphere(m, rho_ratio):
    """Âncora teórica: x_ref = sqrt(3/(m*mt)), mesma forma usada no caso
    'mixed' do core-shell. Aqui mt = m/rho_ratio (ver
    sphere_energy_parts_vs_xM no pipeline), então:
        x_ref = sqrt(3/(m*mt)) = sqrt(3*rho_ratio/m**2) = sqrt(3*rho_ratio)/m
    """
    m, rho_ratio = np.asarray(m, dtype=float), np.asarray(rho_ratio, dtype=float)
    mt = m / rho_ratio
    return np.sqrt(3.0 / (m * mt))


