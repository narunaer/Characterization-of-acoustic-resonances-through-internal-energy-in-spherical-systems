# Confirmacao/refinamento de picos por derivada (em vez de confiar so na
# "proeminencia" da deteccao numa malha fixa, exige a condicao matematica
# de maximo local de verdade: dW/dx = 0 trocando de sinal de + para -, e
# d2W/dx2 < 0). A derivada numerica usa diferenca central de 4a ordem
# (equivale a extrapolacao de Richardson, elimina o erro O(h^2)).
#
# A resolucao da varredura acompanha o periodo fisico esperado pi/m das
# oscilacoes (em vez da malha global fixa), o que evita o aliasing que
# aparece pra m grande (oscilacao mais rapida que a amostragem de
# N_GLOBAL_POINTS). Os candidatos da deteccao original (proeminencia + D0)
# so servem pra herdar metadados (D0_confirmado etc.) quando ha
# correspondencia proxima -- nao sao usados como ancora da busca.
# ---------------------------------------------------------------------
