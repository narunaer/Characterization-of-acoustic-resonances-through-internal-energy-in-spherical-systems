# ============================================================
# BESSEL E HANKEL ESFÉRICAS
#
# IMPORTANTE:
#
# j_{-n-1}(x) = (-1)^(n+1) y_n(x)
# y_{-n-1}(x) = (-1)^n j_n(x)
#
# portanto, para índice negativo q:
#
# j_q(x) = (-1)^(-q) y_{-q-1}(x)
# y_q(x) = (-1)^(-q-1) j_{-q-1}(x)
#
# ============================================================

def J(n, x):
    x = np.asarray(x, dtype=float)

    if n >= 0:
        return spherical_jn(n, x)

    return (-1) ** (-n) * spherical_yn(-n - 1, x)


def Y(n, x):
    x = np.asarray(x, dtype=float)

    if n >= 0:
        return spherical_yn(n, x)

    return (-1) ** (-n - 1) * spherical_jn(-n - 1, x)


def dJ(n, x):
    x = np.asarray(x, dtype=float)

    if n >= 0:
        return spherical_jn(n, x, derivative=True)

    return (
        (-1) ** (-n)
        * spherical_yn(
            -n - 1,
            x,
            derivative=True
        )
    )


def dY(n, x):
    x = np.asarray(x, dtype=float)

    if n >= 0:
        return spherical_yn(n, x, derivative=True)

    return (
        (-1) ** (-n - 1)
        * spherical_jn(
            -n - 1,
            x,
            derivative=True
        )
    )


def H(n, x):
    return J(n, x) + 1j * Y(n, x)


def dH(n, x):
    return dJ(n, x) + 1j * dY(n, x)


