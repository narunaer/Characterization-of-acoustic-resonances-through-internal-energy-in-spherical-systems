def build_latex_table(result, coef_key, err_key, row_labels, caption, label_tag, sig_figs=2):
    lines = [
        r"\begin{table}[ht]",
        r"\centering",
        rf"\caption{{{caption}}}",
        rf"\label{{{label_tag}}}",
        r"\begin{tabular}{lc}",
        r"\toprule",
        rf"\textbf{{Coeff}} & \textbf{{{COLUMN_LABEL}}} \\",
        r"\midrule",
    ]
    coeffs, errors = result[coef_key], result[err_key]
    for i, row_label in enumerate(row_labels):
        lines.append(f"{row_label} & {format_bold_pm_error(coeffs[i], errors[i], sig_figs=sig_figs)} " + r"\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines)


