# ============================================================

def sphere_energy_parts_vs_xM(
    xM_vals,
    m,
    rho_ratio,
    lmax=10
):
    xM_vals = np.asarray(xM_vals, dtype=float)

    if np.any(xM_vals <= 0.0):
        raise ValueError(
            "Todos os valores de x_M devem ser positivos."
        )

    if not np.isfinite(m) or m <= 0.0:
        raise ValueError(
            "m deve ser positivo e finito."
        )

    if (
        not np.isfinite(rho_ratio)
        or rho_ratio <= 0.0
    ):
        raise ValueError(
            "rho_ratio deve ser positivo e finito."
        )

    # --------------------------------------------------------
    # PARÂMETROS ADIMENSIONAIS
    # --------------------------------------------------------

    m_t = float(m) / float(rho_ratio)

    rhoM_over_rhoS = (
        1.0 / float(rho_ratio)
    )

    xS_vals = (
        float(m) * xM_vals
    )

    # --------------------------------------------------------
    # ENERGIAS
    # --------------------------------------------------------

    WP = np.zeros_like(
        xM_vals,
        dtype=float
    )

    WK = np.zeros_like(
        xM_vals,
        dtype=float
    )

    # --------------------------------------------------------
    # SOMA MULTIPOLAR
    # --------------------------------------------------------

    for ell in range(int(lmax) + 1):

        jS = J(
            ell,
            xS_vals
        )

        djS = dJ(
            ell,
            xS_vals
        )

        hM = H(
            ell,
            xM_vals
        )

        dhM = dH(
            ell,
            xM_vals
        )

        # ----------------------------------------------------
        # DENOMINADOR DO COEFICIENTE INTERNO
        # ----------------------------------------------------

        denominator = (
            jS * dhM
            - m_t * djS * hM
        )

        # ----------------------------------------------------
        # COEFICIENTE INTERNO
        # ----------------------------------------------------

        b_ell = np.zeros_like(
            xM_vals,
            dtype=complex
        )

        valid = (
            np.isfinite(denominator)
            & (
                np.abs(denominator)
                > 1e-300
            )
        )

        b_ell[valid] = (
            1j
            * rhoM_over_rhoS
            /
            (
                xM_vals[valid] ** 2
                * denominator[valid]
            )
        )

        modal_weight = (
            (2 * ell + 1)
            * np.abs(b_ell) ** 2
        )

        # ----------------------------------------------------
        # INTEGRAL RADIAL DE LOMMEL
        #
        # aqui aparece J(ell-1)
        #
        # para ell = 0:
        #
        # J(-1,x) = cos(x)/x = -Y(0,x)
        #
        # ----------------------------------------------------

        radial_integral = (
            0.5
            * xS_vals ** 3
            * (
                jS ** 2
                - J(
                    ell - 1,
                    xS_vals
                )
                * J(
                    ell + 1,
                    xS_vals
                )
            )
        )

        # ----------------------------------------------------
        # TERMO DE CONTORNO
        # ----------------------------------------------------

        boundary_term = (
            xS_vals ** 2
            * jS
            * djS
        )

        # ----------------------------------------------------
        # ENERGIA POTENCIAL
        # ----------------------------------------------------

        WP += (
            modal_weight
            * np.real(
                radial_integral
            )
        )

        # ----------------------------------------------------
        # ENERGIA CINÉTICA
        # ----------------------------------------------------

        WK += (
            modal_weight
            * np.real(
                radial_integral
                + boundary_term
            )
        )

    # --------------------------------------------------------
    # LIMPEZA APENAS DE ERROS NUMÉRICOS
    # --------------------------------------------------------

    WP = np.real(WP)
    WK = np.real(WK)

    WP[
        ~np.isfinite(WP)
    ] = np.nan

    WK[
        ~np.isfinite(WK)
    ] = np.nan

    WT = WP + WK

    return WT, WP, WK


def sphere_total_energy_vs_xM(
    xM_vals,
    m,
    rho_ratio,
    lmax=10
):
    WT, _, _ = sphere_energy_parts_vs_xM(
        xM_vals=xM_vals,
        m=m,
        rho_ratio=rho_ratio,
        lmax=lmax
    )

    return WT


