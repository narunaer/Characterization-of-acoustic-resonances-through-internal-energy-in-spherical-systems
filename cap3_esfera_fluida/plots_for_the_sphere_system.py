def build_design_matrix_ancorada(m, rho_ratio, x_n, sphere_ref_fn):
    m, rho_ratio, x_n = (np.asarray(v, dtype=float) for v in (m, rho_ratio, x_n))
    x_ref = sphere_ref_fn(m, rho_ratio)
    lm, lr = np.log(m), np.log(rho_ratio)
    XA = np.column_stack([x_ref, lm * x_ref, lr * x_ref, lm**2 * x_ref, lm * lr * x_ref, lr**2 * x_ref])
    XB = np.column_stack([x_n, lm * x_n, lr * x_n, lm**2 * x_n, lm * lr * x_n, lr**2 * x_n])
    return np.column_stack([XA, XB])


def fit_recurrence_ancorada(curves_df, label, test_fraction, seed, sphere_ref_fn):
    transitions_df = build_transitions(curves_df)
    if len(transitions_df) < 20:
        raise RuntimeError(f"[{label}] poucas transições ({len(transitions_df)}) pra ajustar/testar.")

    train_df, test_df, n_train_curves, n_test_curves = split_train_test_by_curve(transitions_df, test_fraction, seed)

    def build_X(df):
        return build_design_matrix_ancorada(
            df["m"].to_numpy(dtype=float), df["rho_ratio"].to_numpy(dtype=float),
            df["xM_n"].to_numpy(dtype=float), sphere_ref_fn,
        )

    X_train = build_X(train_df)
    y_train = train_df["xM_np1"].to_numpy(dtype=float)
    coefficients, _, rank, sv = np.linalg.lstsq(X_train, y_train, rcond=None)
    coef_errors = coefficient_standard_errors(X_train, y_train, coefficients)

    train_pred = build_X(train_df) @ coefficients
    test_pred = build_X(test_df) @ coefficients

    metrics_train = calculate_metrics(train_df["xM_np1"], train_pred)
    metrics_test = calculate_metrics(test_df["xM_np1"], test_pred)
    condition_number = float(sv[0] / sv[-1]) if len(sv) > 1 and sv[-1] > 0.0 else np.nan

    return {
        "label": label,
        "coefficients": coefficients, "coef_errors": coef_errors, "coef_names": COEF_NAMES_ANCORADA,
        "rank": int(rank), "condition_number": condition_number,
        "n_curves_total": int(len(curves_df)), "n_curves_with_peaks": int((curves_df["n_peaks"] > 0).sum()),
        "n_transitions": len(transitions_df), "n_train_curves": n_train_curves, "n_test_curves": n_test_curves,
        "metrics_train": metrics_train, "metrics_test": metrics_test,
    }


