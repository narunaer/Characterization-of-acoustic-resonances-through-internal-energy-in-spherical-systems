def fit_existence_classifier(curves_df, test_fraction, seed):
    df = curves_df.copy()
    df["log_m"] = np.log(df["m"].to_numpy(dtype=float))
    df["log_rho"] = np.log(df["rho_ratio"].to_numpy(dtype=float))
    df["has_resonance"] = (df["n_peaks"] > 0).astype(int)

    train_df, test_df = split_curves_train_test(df, test_fraction, seed)
    feature_cols = ["log_m", "log_rho"]
    X_train, y_train = train_df[feature_cols].to_numpy(dtype=float), train_df["has_resonance"].to_numpy(dtype=int)
    X_test, y_test = test_df[feature_cols].to_numpy(dtype=float), test_df["has_resonance"].to_numpy(dtype=int)

    # C=1e6 -> regularização ~nula, coeficientes ~= MLE não regularizado
    model = Pipeline([
        ("poly", PolynomialFeatures(degree=2, include_bias=False)),
        ("scale", StandardScaler()),
        ("clf", LogisticRegression(max_iter=2000, C=1e6)),
    ])
    model.fit(X_train, y_train)

    def evaluate(X, y):
        proba = model.predict_proba(X)[:, 1]
        pred = (proba >= 0.5).astype(int)
        m = {
            "N": int(len(y)), "Positive_rate": float(np.mean(y)),
            "Accuracy": float(accuracy_score(y, pred)), "Precision": float(precision_score(y, pred, zero_division=0)),
            "Recall": float(recall_score(y, pred, zero_division=0)), "F1": float(f1_score(y, pred, zero_division=0)),
        }
        m["ROC_AUC"] = float(roc_auc_score(y, proba)) if len(np.unique(y)) == 2 else np.nan
        return m

    metrics_train = evaluate(X_train, y_train)
    metrics_test = evaluate(X_test, y_test)

    scaler, logistic = model.named_steps["scale"], model.named_steps["clf"]
    scaled_coef = logistic.coef_[0].astype(float)
    effective_coefficients = np.concatenate([
        [float(logistic.intercept_[0] - np.sum(scaled_coef * scaler.mean_ / scaler.scale_))],
        scaled_coef / scaler.scale_,
    ])
    coef_errors = classifier_coefficient_standard_errors(
        train_df["m"].to_numpy(dtype=float), train_df["rho_ratio"].to_numpy(dtype=float), effective_coefficients,
    )

    return {
        "formula_coefficients": effective_coefficients, "formula_coef_errors": coef_errors,
        "formula_term_names": CLF_TERM_NAMES, "metrics_train": metrics_train, "metrics_test": metrics_test,
    }


